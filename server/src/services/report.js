function escapeMarkdown(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ')
}

function renderValue(value, depth = 0) {
  if (value === null || value === undefined) return '_null_'
  if (Array.isArray(value)) {
    if (value.length === 0) return '_empty_'
    if (value.every((item) => item === null || typeof item !== 'object')) {
      return value.map((item) => escapeMarkdown(item)).join(', ')
    }
    return value.map((item, index) => `\n${'  '.repeat(depth)}- ${renderValue(item, depth + 1)}`).join('')
  }
  if (typeof value === 'object') {
    return Object.entries(value)
      .map(([key, child]) => `\n${'  '.repeat(depth)}- **${key}**: ${renderValue(child, depth + 1)}`)
      .join('')
  }
  return escapeMarkdown(value)
}

export function renderReportMarkdown({ run, data }) {
  const lines = [
    `# ${run.tool} report`,
    '',
    `- **Target:** ${escapeMarkdown(run.target)}`,
    `- **Status:** ${run.status}`,
    `- **Run ID:** ${run.id}`,
    `- **Created:** ${new Date(run.createdAt).toISOString()}`,
  ]
  if (run.finishedAt) lines.push(`- **Finished:** ${new Date(run.finishedAt).toISOString()}`)
  lines.push('', '## Summary', '')
  if (run.summary && Object.keys(run.summary).length > 0) {
    lines.push('| Key | Value |', '| --- | --- |')
    for (const [key, value] of Object.entries(run.summary)) {
      lines.push(`| ${escapeMarkdown(key)} | ${renderValue(value)} |`)
    }
  } else {
    lines.push('_No summary available._')
  }
  lines.push('', '## Results', '', renderValue(data))
  lines.push('', '---', '', 'Generated by CyberSec Toolkit.')
  return `${lines.join('\n')}\n`
}
